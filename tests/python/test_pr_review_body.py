"""One-line review summary tests (issue #991).

The maintainer decision recorded on issue #991: the review body is replaced
outright by a single line — model plus severity counts — with no heading, no
severity tables, no "generated by" footer, and no setting to turn it off.
Inline comments keep their own Assisted-by signature.

Covers the body itself, the model resolution (PI_MODEL → PI_COMMENT_SIGNATURE →
unknown) and the payload `post_review` hands to `gh api`.
"""

from __future__ import annotations

import json
import subprocess
from typing import Any

import pytest

from myk_pi_tools.comment_signature import review_model
from myk_pi_tools.pr.post_comment import Comment, generate_review_body, post_review


def _comment(body: str, path: str = "src/a.py", line: int = 1) -> Comment:
    return Comment(path=path, line=line, body=body)


@pytest.fixture(autouse=True)
def _clean_model_env(monkeypatch: pytest.MonkeyPatch) -> None:
    """Every test starts with no ambient model, so resolution is explicit."""
    monkeypatch.delenv("PI_MODEL", raising=False)
    monkeypatch.delenv("PI_COMMENT_SIGNATURE", raising=False)


def test_body_is_one_line_with_severity_counts(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("PI_MODEL", "zai-org/glm-5-3")
    comments = [
        _comment("### [CRITICAL] injection", "a.py", 1),
        _comment("### [WARNING] missing check", "b.py", 2),
        _comment("### [SUGGESTION] rename", "c.py", 3),
        # No severity marker defaults to SUGGESTION.
        _comment("plain body", "d.py", 4),
    ]

    body = generate_review_body(comments)

    assert body == ("Reviewed by PI (zai-org/glm-5-3) — found 4 issue(s): 1 critical, 1 warnings, 2 suggestions.")
    assert "\n" not in body


def test_body_has_no_heading_tables_or_footer(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("PI_MODEL", "model-x")
    body = generate_review_body([_comment("### [WARNING] w", "a.py", 7)])

    for gone in ("## Code Review", "| File |", "|------", "Found **", "Review generated by pi", "---"):
        assert gone not in body


def test_zero_comments_still_renders_the_line(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("PI_MODEL", "model-x")

    assert generate_review_body([]) == (
        "Reviewed by PI (model-x) — found 0 issue(s): 0 critical, 0 warnings, 0 suggestions."
    )


def test_model_falls_back_to_the_session_signature(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("PI_COMMENT_SIGNATURE", "Assisted-by: PI (claude-opus-4-6)")

    assert review_model() == "claude-opus-4-6"


def test_operation_model_wins_over_the_session_signature(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("PI_MODEL", "operation-model")
    monkeypatch.setenv("PI_COMMENT_SIGNATURE", "Assisted-by: PI (session-model)")

    assert review_model() == "operation-model"


def test_invalid_operation_model_falls_through(monkeypatch: pytest.MonkeyPatch) -> None:
    # A model id with a newline would break the line; it must not be printed.
    monkeypatch.setenv("PI_MODEL", "bad\nmodel")
    monkeypatch.setenv("PI_COMMENT_SIGNATURE", "Assisted-by: PI (session-model)")

    assert review_model() == "session-model"


def test_unknown_when_nothing_is_set() -> None:
    assert review_model() == "unknown"
    assert generate_review_body([_comment("x")]) == (
        "Reviewed by PI (unknown) — found 1 issue(s): 0 critical, 0 warnings, 1 suggestions."
    )


def test_posted_payload_carries_the_line_and_keeps_inline_signatures(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    monkeypatch.setenv("PI_MODEL", "zai-org/glm-5-3")
    monkeypatch.setenv("PI_COMMENT_SIGNATURE", "Assisted-by: PI (zai-org/glm-5-3)")
    captured: dict[str, str] = {}

    def fake_run(argv: list[str], **kwargs: Any) -> subprocess.CompletedProcess[str]:
        assert argv[:2] == ["gh", "api"]
        captured["payload"] = str(kwargs["input"])
        return subprocess.CompletedProcess(args=argv, returncode=0, stdout="{}", stderr="")

    monkeypatch.setattr("myk_pi_tools.pr.post_comment.subprocess.run", fake_run)

    result = post_review(
        "myk-org/pi-config",
        "991",
        "deadbeef",
        [_comment("### [CRITICAL] injection", "src/a.py", 12)],
    )

    payload = json.loads(captured["payload"])
    assert result.status == "success"
    assert payload["event"] == "COMMENT"
    assert payload["body"] == (
        "Reviewed by PI (zai-org/glm-5-3) — found 1 issue(s): 1 critical, 0 warnings, 0 suggestions."
    )
    # The summary names the model, so it carries no separate Assisted-by footer.
    assert "Assisted-by" not in payload["body"]
    # Inline comments stay signed: /pr-review dedup relies on it.
    assert payload["comments"][0]["body"].endswith("*Assisted-by: PI (zai-org/glm-5-3)*")
